import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.api.artifacts.VersionCatalogsExtension
import org.gradle.api.file.FileCollection
import org.gradle.api.tasks.JavaExec
import org.gradle.kotlin.dsl.getByType
import org.gradle.kotlin.dsl.register
import org.jetbrains.kotlin.gradle.dsl.KotlinMultiplatformExtension
import org.jetbrains.kotlin.gradle.plugin.KotlinCompilation
import org.jetbrains.kotlin.gradle.targets.jvm.KotlinJvmTarget

/**
 * Adds a `pitest` task, mutation testing of the JVM unit tests, to a Kotlin Multiplatform module with a `jvm()` target
 * (Notion N-18).
 *
 * It runs the PIT command line through `JavaExec`: the `info.solidsoft.pitest` Gradle plugin needs the `java` plugin,
 * which Kotlin Multiplatform rejects. It is report only, so there is no score threshold; the task fails only when
 * Pitest itself fails, for example on a failing test. It isn't part of `check` or `build`.
 *
 * The mutated classes are those of the module's own package, which follows its path (`:core:domain` is
 * `com.vamvisions.verbeclair.core.domain`). Reports are written to `build/reports/pitest`.
 *
 * A module whose tests need a system property passes it on with `--jvmArgs`, because Pitest runs the tests in a JVM
 * of its own.
 */
class PitestConventionPlugin : Plugin<Project> {
    override fun apply(target: Project) {
        with(target) {
            val libs = extensions.getByType<VersionCatalogsExtension>().named("libs")
            configurations.resolvable(PITEST_CONFIGURATION)
            dependencies.add(PITEST_CONFIGURATION, libs.findLibrary("pitest-commandLine").get())

            pluginManager.withPlugin("org.jetbrains.kotlin.multiplatform") {
                extensions
                    .getByType<KotlinMultiplatformExtension>()
                    .targets
                    .withType(KotlinJvmTarget::class.java)
                    .configureEach {
                        registerPitest(
                            main = compilations.getByName(KotlinCompilation.MAIN_COMPILATION_NAME),
                            test = compilations.getByName(KotlinCompilation.TEST_COMPILATION_NAME),
                        )
                    }
            }
        }
    }

    private fun Project.registerPitest(main: KotlinCompilation<*>, test: KotlinCompilation<*>) {
        // Plain file collections and strings: the configuration cache can't store a Kotlin compilation, so the argument
        // provider must not capture one.
        val testRuntime =
            files(
                test.output.allOutputs,
                main.output.allOutputs,
                requireNotNull(test.runtimeDependencyFiles) { "the JVM test compilation has no runtime classpath" },
            )
        val mutableCode: FileCollection = main.output.classesDirs
        val sourceDirs = listOf("src/commonMain/kotlin", "src/jvmMain/kotlin").map { file(it).absolutePath }
        val reportDir = layout.buildDirectory.dir(REPORT_DIR)
        val ownPackage = "$ROOT_PACKAGE${path.replace(':', '.')}.*"

        tasks.register<JavaExec>("pitest") {
            group = "verification"
            description = "Mutation testing of the JVM unit tests with Pitest. Report only, not part of check."
            dependsOn(test.compileTaskProvider)
            inputs.files(testRuntime)
            classpath = configurations.getByName(PITEST_CONFIGURATION)
            mainClass.set(PITEST_MAIN_CLASS)
            argumentProviders.add {
                listOf(
                    "--reportDir=${reportDir.get().asFile.absolutePath}",
                    "--classPath=${testRuntime.existingPaths()}",
                    "--includeLaunchClasspath=false",
                    "--mutableCodePaths=${mutableCode.existingPaths()}",
                    "--sourceDirs=${sourceDirs.joinToString(",")}",
                    "--targetClasses=$ownPackage",
                    "--targetTests=$ownPackage",
                    // The compiler adds null checks as calls to this package; no test can be expected to notice them.
                    "--avoidCallsTo=kotlin.jvm.internal",
                    // Generated by Room and kotlinx.serialization.
                    "--excludedClasses=*_Impl,*_Impl$*,*DatabaseConstructor,*$\$serializer",
                    "--outputFormats=XML,HTML",
                    "--timestampedReports=false",
                )
            }
        }
    }

    private fun FileCollection.existingPaths(): String = filter { it.exists() }.joinToString(",") { it.absolutePath }

    private companion object {
        const val PITEST_CONFIGURATION = "pitest"
        const val PITEST_MAIN_CLASS = "org.pitest.mutationtest.commandline.MutationCoverageReport"
        const val REPORT_DIR = "reports/pitest"
        const val ROOT_PACKAGE = "com.vamvisions.verbeclair"
    }
}
